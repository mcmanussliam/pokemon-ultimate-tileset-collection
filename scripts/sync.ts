/**
 * Imports the source Google Sheet into browsable folders and a JSON catalogue.
 * This metadata importer does NOT redistribute artist image files.
 */
import ExcelJS from 'exceljs';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, writeFileSync, statSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type Entry = {
  id: string; title: string; artist: string; category_1: string; category_2: string;
  generation: string; source_platform: string; source_url: string; credits: string;
  number: string; sheet: string; sheet_row: number; folder: string;
  subcategory: string; preview_url: string; preview_source: string;
};
type Raw = Omit<Entry, 'id' | 'folder' | 'subcategory' | 'preview_url' | 'preview_source'>;
type Catalogue = { source_spreadsheet: string; last_synced: string; total: number; entries: Entry[] };

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SHEET_ID = '1hy3DqFFUu_H6Ddibr5evoqGW8aVSPHxSH6cZWuu9IR8';
const ORIGINAL = 'https://docs.google.com/spreadsheets/d/' + SHEET_ID + '/edit?gid=0#gid=0';
const SOURCE_TITLES: Record<string, string> = JSON.parse(readFileSync(join(ROOT, '_catalog/source-titles.json'), 'utf8'));
const CATEGORY_ALIASES: Record<string, string> = {
  beachers: 'beaches', 'mega-collection': 'collections', collection: 'collections',
  'pokemon-fr-lg': 'pokemon-frlg', 'pokemon-hg-ss': 'pokemon-hgss',
};
const NOTE = '<!-- Generated by scripts/sync.ts; edit the original spreadsheet or tooling instead. -->';
const CATEGORY_SLUGS = ['outdoor-tilesets', 'indoor-tilesets', 'indoor-outdoor-tilesets',
  'misc-tilesets', 'animated-tilesets', 'auto-tilesets', 'in-out-misc-etc'];

function slug(input: string): string {
  return String(input || '').normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'untitled';
}
function shortSlug(title: string, artist: string): string {
  let name = title.replace(/\s+on DeviantArt$/i, '').replace(/\s*\|\s*Eevee Expo$/i, '')
    .replace(/\s*-\s*The Spriters Resource$/i, '');
  const by = ' by ' + artist.trim();
  if (artist.trim() && name.toLowerCase().endsWith(by.toLowerCase())) name = name.slice(0, -by.length);
  const stem = slug(name).slice(0, 62).replace(/-+$/g, '');
  const person = slug(artist).slice(0, 24).replace(/-+$/g, '');
  return stem + (person && !stem.endsWith(person) ? '-' + person : '');
}
function escapeMd(s: string): string {
  return String(s || '').replace(/\\/g, '\\\\').replace(/([[\]|*<>])/g, '\\$1').replace(/\s+/g, ' ').trim();
}
function safeUrl(s: string): string {
  try {
    const url = new URL(String(s || '').trim());
    return ['https:', 'http:'].includes(url.protocol) ? url.toString() : '';
  } catch { return ''; }
}
function readText(path: string): string { return readFileSync(path, 'utf8'); }
function writeGenerated(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path)) {
    const old = readText(path);
    if (old === text) return;
    if (!old.startsWith('<!-- Generated by scripts/')) {
      console.log('Preserving hand-edited file: ' + path);
      return;
    }
  }
  writeFileSync(path, text);
}
function writeMetadata(path: string, entry: Entry): void {
  if (existsSync(path)) {
    try {
      const prior = JSON.parse(readText(path));
      if (prior._generated_by !== 'scripts/sync.ts') {
        console.log('Preserving hand-edited metadata: ' + path);
        return;
      }
    } catch {
      console.log('Preserving non-JSON metadata: ' + path);
      return;
    }
  }
  writeFileSync(path, JSON.stringify({ ...entry, _generated_by: 'scripts/sync.ts' }, null, 2) + '\n');
}
function cellText(cell: ExcelJS.Cell): string {
  const value = cell.value;
  if (value && typeof value === 'object') {
    if ('text' in value && typeof value.text === 'string') return value.text.trim();
    if ('result' in value && value.result != null) {
      const result = value.result;
      if (typeof result === 'string' || typeof result === 'number') return String(result).trim();
      if (typeof result === 'object') {
        if ('richText' in result && Array.isArray(result.richText)) {
          return result.richText.map(v => v.text).join('').trim();
        }
        if ('text' in result && typeof result.text === 'string') return result.text.trim();
      }
    }
    if ('richText' in value && Array.isArray(value.richText)) {
      return value.richText.map(v => v.text).join('').trim();
    }
  }
  return String(cell.text || '').trim();
}
function cellHref(cell: ExcelJS.Cell): string {
  const value = cell.value;
  if (value && typeof value === 'object' && 'hyperlink' in value) return safeUrl(String(value.hyperlink));
  const link = (cell as ExcelJS.Cell & { hyperlink?: string }).hyperlink;
  if (link) return safeUrl(link);
  if (value && typeof value === 'object' && 'formula' in value && typeof value.formula === 'string') {
    const m = value.formula.match(/HYPERLINK\(\s*"([^"]+)"/i);
    if (m) return safeUrl(m[1]);
  }
  return safeUrl(cellText(cell));
}
function findHeaders(row: ExcelJS.Row): Record<string, number> | undefined {
  const result: Record<string, number> = {};
  row.eachCell({ includeEmpty: false }, (cell, col) => {
    const key = cellText(cell).toLowerCase().replace(/[^a-z0-9]/g, '');
    const names: Record<string, string> = {
      artistsubmitter: 'artist', artist: 'artist', submitter: 'artist',
      category1: 'category_1', primarycategory: 'category_1',
      category2: 'category_2', secondarycategory: 'category_2',
      generation: 'generation', gen: 'generation',
      source: 'source_platform', website: 'source_platform',
      link: 'title', sourcelink: 'title', tilesetlink: 'title', tileset: 'title',
      credits: 'credits', credit: 'credits', number: 'number', no: 'number', id: 'number',
    };
    if (names[key]) result[names[key]] = col;
  });
  return result.title && (result.artist || result.credits) ? result : undefined;
}
async function readSpreadsheet(): Promise<Raw[]> {
  const provided = process.argv.find(x => x.startsWith('--xlsx='));
  const bytes = provided ? readFileSync(provided.slice('--xlsx='.length)) :
    Buffer.from(await (async () => {
      const url = 'https://docs.google.com/spreadsheets/d/' + SHEET_ID + '/export?format=xlsx';
      const response = await fetch(url, { signal: AbortSignal.timeout(90000) });
      if (!response.ok) throw new Error('Spreadsheet download failed: HTTP ' + response.status);
      return response.arrayBuffer();
    })());
  const book = new ExcelJS.Workbook();
  await book.xlsx.load(bytes as any);
  const rows: Raw[] = [];
  book.eachSheet(sheet => {
    if (!CATEGORY_SLUGS.includes(slug(sheet.name))) return;
    let headers: Record<string, number> | undefined;
    sheet.eachRow({ includeEmpty: false }, (row, number) => {
      const h = findHeaders(row);
      if (h) { headers = h; return; }
      if (!headers) return;
      const value = (key: string) => headers?.[key] ? cellText(row.getCell(headers[key])) : '';
      const sourceCell = row.getCell(headers.title);
      const artworkUrl = cellHref(sourceCell);
      let title = value('title');
      if (!title || title === '[object Object]') title = SOURCE_TITLES[artworkUrl] || title;
      if (!title || title === '[object Object]' || /^(link|n\/a|-)$/i.test(title)) return;
      rows.push({
        title, artist: value('artist'), category_1: value('category_1'),
        category_2: value('category_2'), generation: value('generation'),
        source_platform: value('source_platform'), source_url: artworkUrl,
        credits: value('credits'), number: value('number').replace(/\.0+$/, ''),
        sheet: sheet.name, sheet_row: number,
      });
    });
  });
  return rows;
}
function sourceRow(entry: Entry): string {
  // XLSX sheet IDs are not the same as the Google Sheets tab gid.
  // Only the known outdoor gid=0 is linked directly; other tabs use the source document.
  return entry.sheet === 'Outdoor Tilesets'
    ? 'https://docs.google.com/spreadsheets/d/' + SHEET_ID + '/edit?gid=0#range=A' + entry.sheet_row
    : ORIGINAL;
}
function assetName(dir: string): string {
  if (!existsSync(dir)) return '';
  const files = readdirSync(dir).filter(f => /^(tileset|preview)\.(png|jpg|jpeg|gif|webp)$/i.test(f));
  return files.find(f => /^tileset\./i.test(f)) || files[0] || '';
}
function entryReadme(e: Entry): string {
  const fields: Array<[string, string]> = [
    ['Creator / submitter', e.artist], ['Sheet', e.sheet],
    ['Primary category', e.category_1], ['Secondary category', e.category_2],
    ['Generation', e.generation], ['Platform', e.source_platform],
    ['Spreadsheet entry number', e.number],
  ];
  const details = fields.filter(([, v]) => !!v).map(([k, v]) => '- **' + k + ':** ' + escapeMd(v)).join('\n');
  const credit = e.credits.includes('☆') ? 'Artist credit required (as flagged by the spreadsheet).' :
    e.credits.includes('❉') ? 'Artist credit is unspecified/optional on the sheet; still credit the artist where possible.' :
    'Check the creator page for specific credit requirements.';
  const asset = assetName(join(ROOT, e.folder));
  const preview = asset ? '![' + escapeMd(e.title) + '](./' + asset + ')' :
    e.preview_url ? '![' + escapeMd(e.title) + ' (source-hosted preview)](' + e.preview_url + ')' :
    'No verified image preview is available here yet. [View the artwork at its original source](' + (e.source_url || ORIGINAL) + ').';
  return [
    NOTE, '# ' + escapeMd(e.title), '',
    '> An entry in the [original Pokémon Ultimate Tileset Collection spreadsheet](' + ORIGINAL + ').',
    '> This repository is an unofficial **readability fork**, not the creator of the artwork.', '',
    '## Preview', '', preview, '',
    asset ? 'Locally stored artwork: confirm redistribution permission with the artist before reuse.' :
      e.preview_url ? 'This preview is loaded directly from the source site; the image is **not redistributed** here.' :
        'The image is not copied to GitHub without confirmation that redistribution is allowed.',
    '', '## Details', '', details, '', '## Source and attribution', '',
    '- **Original artwork page:** ' + (e.source_url ? '[Open creator/source](' + e.source_url + ')' : 'See the original spreadsheet'),
    '- **Original spreadsheet entry:** [Open sheet](' + sourceRow(e) + ')',
    '- **Credit note:** ' + credit,
    '- **Usage:** The sheet describes its entries as **non-commercial**. Check the artist page for the exact terms; non-commercial use does not automatically allow redistribution.',
    '', 'This index does not grant a licence for the artwork.', ''
  ].join('\n');
}
function listing(title: string, desc: string, items: Entry[]): string {
  return [NOTE, '# ' + escapeMd(title), '',
    desc, '', '**' + items.length + ' tilesets**', '',
    ...items.sort((a,b) => a.title.localeCompare(b.title)).map(e =>
      '- [' + escapeMd(e.title) + '](' + e.folder.split('/').at(-1) + '/)' +
      (e.artist ? ' by ' + escapeMd(e.artist) : '')), ''
  ].join('\n');
}
function migrateFolder(previous: string, next: string): void {
  if (previous === next || !existsSync(join(ROOT, previous))) return;
  mkdirSync(dirname(join(ROOT, next)), { recursive: true });
  const source = join(ROOT, previous), dest = join(ROOT, next);
  if (!existsSync(dest)) {
    renameSync(source, dest);
  } else {
    // Never delete user-contributed files when paths collide.
    for (const file of readdirSync(source)) {
      const from = join(source, file), to = join(dest, file);
      if (!existsSync(to)) renameSync(from, to);
    }
    if (readdirSync(source).length === 0) rmSync(source, { recursive: true });
  }
}
function loadOld(): Entry[] {
  const file = join(ROOT, '_catalog', 'catalog.json');
  if (!existsSync(file)) return [];
  try { return (JSON.parse(readText(file)).entries || []) as Entry[]; }
  catch { return []; }
}
function main(): Promise<void> {
  return (async () => {
    const old = loadOld();
    const existing = new Map<string, Entry>();
    for (const e of old) {
      existing.set(e.source_url || e.sheet + '|' + e.sheet_row + '|' + e.title, e);
    }
    const sheetRows = await readSpreadsheet();
    if (sheetRows.length < 500) throw new Error('Expected the public sheet to contain hundreds of entries; refusing destructive partial import.');
    const used = new Set<string>();
    const entries: Entry[] = sheetRows.map(raw => {
      const category = slug(raw.sheet);
      const primary = CATEGORY_ALIASES[slug(raw.category_1)] || slug(raw.category_1 || 'general');
      const itemBase = shortSlug(raw.title, raw.artist);
      let folder = category + '/' + primary + '/' + itemBase;
      if (used.has(folder)) folder += '-' + (raw.number ? slug(raw.number) : String(raw.sheet_row));
      used.add(folder);
      const previous = existing.get(raw.source_url || raw.sheet + '|' + raw.sheet_row + '|' + raw.title);
      return {
        ...raw, id: slug(raw.source_url || raw.sheet + '-' + raw.sheet_row).slice(-90),
        subcategory: primary, folder,
        preview_url: safeUrl(/ee_icon|\/styles\/default|favicon|logo|placeholder/i.test(previous?.preview_url || '') ? '' : (previous?.preview_url || (/\.(png|jpe?g|gif|webp)(\?|$)/i.test(raw.source_url) ? raw.source_url : ''))), preview_source: previous?.preview_source || '',
      };
    });
    const byCategory = new Map<string, Entry[]>();
    const bySubcategory = new Map<string, Entry[]>();
    for (const e of entries) {
      const key = e.source_url || e.sheet + '|' + e.sheet_row + '|' + e.title;
      const previous = existing.get(key);
      if (previous?.folder && previous.folder !== e.folder) migrateFolder(previous.folder, e.folder);
      const target = join(ROOT, e.folder);
      mkdirSync(target, { recursive: true });
      const localArtwork = assetName(target);
      if (localArtwork) {
        e.preview_url = 'https://raw.githubusercontent.com/mcmanussliam/pokemon-ultimate-tileset-collection/main/' +
          e.folder.split('/').map(encodeURIComponent).join('/') + '/' + encodeURIComponent(localArtwork);
        e.preview_source = 'Creator-authorised file in this repository';
      }
      writeGenerated(join(target, 'README.md'), entryReadme(e));
      writeMetadata(join(target, 'metadata.json'), e);
      const category = e.folder.split('/')[0];
      byCategory.set(category, [...(byCategory.get(category) || []), e]);
      bySubcategory.set(category + '/' + e.subcategory, [...(bySubcategory.get(category + '/' + e.subcategory) || []), e]);
    }
    for (const [key, items] of bySubcategory) {
      const [category, sub] = key.split('/');
      writeGenerated(join(ROOT, key, 'README.md'),
        listing(sub.replace(/-/g, ' '), 'Tilesets from **' + category.replace(/-/g, ' ') + '**. [Original sheet](' + ORIGINAL + ').', items));
    }
    for (const [category, items] of byCategory) {
      const grouped = [...new Set(items.map(e => e.subcategory))].sort();
      const section = grouped.map(sub => {
        const count = items.filter(e => e.subcategory === sub).length;
        return '- [' + sub.replace(/-/g, ' ') + '](' + sub + '/): ' + count + ' tilesets';
      }).join('\n');
      writeGenerated(join(ROOT, category, 'README.md'), [
        NOTE, '# ' + items[0].sheet, '',
        'Browsable version of the [original source spreadsheet](' + ORIGINAL + '). This is an unofficial readability fork.',
        '', '**' + items.length + ' tilesets in ' + grouped.length + ' subcategories**', '', section, ''
      ].join('\n'));
    }
    const catalog: Catalogue = { source_spreadsheet: ORIGINAL, last_synced: new Date().toISOString(),
      total: entries.length, entries };
    const target = join(ROOT, '_catalog', 'catalog.json');
    mkdirSync(dirname(target), { recursive: true });
    // Keep last_synced constant when source and metadata haven't changed.
    if (existsSync(target)) {
      try {
        const prior = JSON.parse(readText(target)) as Catalogue;
        if (JSON.stringify(prior.entries) === JSON.stringify(entries)) catalog.last_synced = prior.last_synced || catalog.last_synced;
      } catch { /* regenerate */ }
    }
    writeFileSync(target, JSON.stringify(catalog, null, 2) + '\n');
    console.log('Synced ' + entries.length + ' tilesets in ' + byCategory.size + ' categories and ' + bySubcategory.size + ' subcategories.');
  })();
}
main().catch(error => { console.error(error); process.exitCode = 1; });
