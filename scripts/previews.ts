/**
 * Find source-hosted social preview images. This does not download/rehost artwork.
 * Run with: npm run previews -- --limit=90 (or --force to retry cached failures).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = join(ROOT, '_catalog/catalog.json');
const checkedPath = join(ROOT, '_catalog/preview-checks.json');
const source = JSON.parse(readFileSync(catalogPath, 'utf8')) as { entries: Entry[]; [key: string]: unknown };
type Entry = { folder: string; title: string; source_url: string; preview_url?: string; preview_source?: string; [key: string]: unknown };
type Check = Record<string, string>;
const checks: Check = existsSync(checkedPath) ? JSON.parse(readFileSync(checkedPath, 'utf8')) : {};
const limit = Number(process.argv.find(a => a.startsWith('--limit='))?.split('=')[1] || 90);
const force = process.argv.includes('--force');

function md(s: string): string { return s.replace(/([[\]|*])/g, '\\$1'); }
function safeUrl(raw: string): string {
  try {
    const url = new URL(raw);
    return url.protocol === 'https:' ? url.toString() : '';
  } catch { return ''; }
}
function decodeHtml(s: string): string {
  return s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/&#x27;/gi, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>');
}
function metaPreview(html: string): string {
  const tags = html.slice(0, 300000).match(/<meta\b[^>]*>/gi) || [];
  for (const tag of tags) {
    const attrs: Record<string, string> = {};
    for (const m of tag.matchAll(/([a-zA-Z:-]+)\s*=\s*(["'])(.*?)\2/g)) {
      attrs[m[1].toLowerCase()] = decodeHtml(m[3]);
    }
    if (['og:image', 'twitter:image', 'twitter:image:src'].includes(attrs.property || attrs.name || '')) {
      const url = safeUrl(attrs.content || '');
      if (url && !/avatar|favicon|default-logo|placeholder/i.test(new URL(url).pathname)) return url;
    }
  }
  return '';
}
async function findPreview(entry: Entry): Promise<string> {
  const url = safeUrl(entry.source_url);
  if (!url) return '';
  try {
    const response = await fetch(url, {
      headers: { 'User-Agent': 'Mozilla/5.0 (compatible; TilesetGallery/1.0)', Accept: 'text/html' },
      signal: AbortSignal.timeout(9000), redirect: 'follow',
    });
    if (!response.ok || !(response.headers.get('content-type') || '').includes('text/html')) return '';
    const body = await response.text();
    return metaPreview(body);
  } catch { return ''; }
}
function updateEntryFiles(entry: Entry): void {
  const metadataPath = join(ROOT, entry.folder, 'metadata.json');
  if (existsSync(metadataPath)) {
    const original = readFileSync(metadataPath, 'utf8');
    try {
      const data = JSON.parse(original);
      if (data._generated_by === 'scripts/sync.ts') {
        writeFileSync(metadataPath, JSON.stringify({ ...entry, _generated_by: 'scripts/sync.ts' }, null, 2) + '\n');
      }
    } catch { /* preserve hand-edited metadata */ }
  }
  const readmePath = join(ROOT, entry.folder, 'README.md');
  if (!existsSync(readmePath)) return;
  let mdFile = readFileSync(readmePath, 'utf8');
  if (!mdFile.startsWith('<!-- Generated by scripts/')) return;
  // Never overwrite an artist image already curated in the folder.
  if (/\!\[[^\]]*\]\(\.\/(?:tileset|preview)\.(?:png|jpe?g|gif|webp)\)/i.test(mdFile)) return;
  const i = mdFile.indexOf('## Preview\n');
  const j = mdFile.indexOf('\n## Details\n', i);
  if (i < 0 || j < 0) return;
  const previewText = '## Preview\n\n![' + md(entry.title) + ' — source-hosted preview](' + entry.preview_url +
    ')\n\nThis preview is loaded directly from the original source site; the image is **not redistributed** here.\n';
  mdFile = mdFile.slice(0, i) + previewText + mdFile.slice(j);
  writeFileSync(readmePath, mdFile);
}
async function main(): Promise<void> {
  const now = new Date();
  const minTime = now.getTime() - 30 * 86400000;
  const candidates = source.entries.filter(entry => {
    const key = entry.source_url;
    if (!key || entry.preview_url) return false;
    if (!force && checks[key] && Date.parse(checks[key]) > minTime) return false;
    return true;
  }).slice(0, Math.max(0, limit));
  let success = 0;
  let cursor = 0;
  const workers = Array.from({ length: Math.min(6, candidates.length) }, async () => {
    while (cursor < candidates.length) {
      const entry = candidates[cursor++];
      const preview = await findPreview(entry);
      checks[entry.source_url] = new Date().toISOString();
      if (preview) {
        entry.preview_url = preview;
        entry.preview_source = 'Original creator page: Open Graph image';
        updateEntryFiles(entry);
        success++;
      }
    }
  });
  await Promise.all(workers);
  writeFileSync(catalogPath, JSON.stringify(source, null, 2) + '\n');
  writeFileSync(checkedPath, JSON.stringify(checks, null, 2) + '\n');
  console.log('Inspected ' + candidates.length + ' source pages; found ' + success + ' source-hosted image previews.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
